// The Detonation Chamber on real Amazon Bedrock (m5-detonation, REQ-03).
//
//   AWS_PROFILE=<profile> AWS_REGION=<region> pnpm exec tsx scripts/detonation-eval.ts
//
// Runs the 20 labelled texts in fixtures/detonation/ through the chamber and
// writes docs/DETONATION.md with the confusion matrix, exactly as measured.
// The model is the fast ("haiku") role: EXORCIST_BEDROCK_HAIKU, else Claude
// Haiku 4.5 through the inference profile for AWS_REGION.
//
// Cost guard: a HARD cap of 60 model calls (at most 2 per text, so 40 are
// needed). Every attempt counts, failed or not; at the cap the script stops
// and the texts not run are reported as "not run". If every call fails (no
// credentials, no model access), nothing is written: no results are made up.
// Prints verdicts and counts only; never prompts, file contents or secrets.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BedrockClientImpl, detonate, modelIdFor } from '../packages/core/src/llm/bedrock.js';
import type { ChamberClient, ChamberRequest, ChamberResult, DetonationReport, Placement } from '../packages/core/src/llm/bedrock.js';

const root = join(import.meta.dirname, '..');
export const HARD_CAP = 60;

type Entry = { file: string; placement: Placement };
type Labels = { attacks: Entry[]; benign: Entry[] };
export type Row = { file: string; label: 'attack' | 'benign'; placement: Placement; report: DetonationReport | null };

/** A client that refuses every call past `cap`, so the script can never spend more. */
export function capped(inner: ChamberClient, cap: number): ChamberClient & { attempts: () => number; failures: () => number; firstError: () => string | null } {
  let attempts = 0;
  let failures = 0;
  let first: string | null = null;
  return {
    attempts: () => attempts,
    failures: () => failures,
    firstError: () => first,
    async converse(req: ChamberRequest): Promise<ChamberResult> {
      if (attempts >= cap) return { ok: false, error: 'hard cap reached' };
      attempts++;
      const r = await inner.converse(req);
      if (!r.ok) { failures++; first ??= r.error.split('\n')[0]?.slice(0, 200) ?? r.error; }
      return r;
    },
  };
}

export async function runEval(client: ReturnType<typeof capped>, labels: Labels, cap: number): Promise<Row[]> {
  const rows: Row[] = [];
  const all = [...labels.attacks.map((e) => ({ ...e, label: 'attack' as const })), ...labels.benign.map((e) => ({ ...e, label: 'benign' as const }))];
  for (const e of all) {
    // Each detonation needs up to 2 calls: never start one that the cap could cut short.
    if (client.attempts() + 2 > cap) { rows.push({ ...e, report: null }); continue; }
    const text = readFileSync(join(root, 'fixtures/detonation', e.file), 'utf8');
    const report = await detonate(text, e.placement, client, { fileName: e.file });
    rows.push({ ...e, report });
    // The first text got no answer at all: credentials or model access are missing. Stop spending attempts.
    if (rows.length === 1 && client.failures() === client.attempts()) { console.error(`first call failed: ${client.firstError() ?? ''}`); break; }
    console.log(`${e.label.padEnd(6)} ${e.file.padEnd(40)} ${report.verdict.padEnd(12)} ${report.modelCalls} call(s)`);
  }
  return rows;
}

const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

export function renderReport(rows: Row[], meta: { model: string; date: string; calls: number; failures: number; cap: number }): string {
  const count = (label: Row['label'], v: string) => rows.filter((r) => r.label === label && (r.report?.verdict ?? 'not run') === v).length;
  const cols = ['detonated', 'inert', 'inconclusive', 'not run'] as const;
  const atk = cols.map((c) => count('attack', c));
  const ben = cols.map((c) => count('benign', c));
  const nA = rows.filter((r) => r.label === 'attack').length;
  const nB = rows.filter((r) => r.label === 'benign').length;
  const lines = [
    '# Detonation Chamber: measured results',
    '',
    'Generated by `scripts/detonation-eval.ts` on the labelled set in `fixtures/detonation/`',
    '(10 reworded attacks that no signature catches, 10 benign look-alikes). Reported exactly as measured,',
    'including misses and false alarms. Nothing here is edited by hand.',
    '',
    `- Model: \`${meta.model}\` on Amazon Bedrock, temperature 0, at most 2 turns and 1,024 output tokens per turn`,
    `- Date: ${meta.date}`,
    `- Model calls: ${meta.calls} (${meta.failures} failed), hard cap ${meta.cap}`,
    '- No tool call was executed; every tool result the model saw was fake, and every secret it could reach was a random fake planted for that run.',
    '',
    '## Confusion matrix',
    '',
    '| | detonated | inert | inconclusive | not run |',
    '|---|---|---|---|---|',
    `| **attack** (${nA}) | ${atk.join(' | ')} |`,
    `| **benign** (${nB}) | ${ben.join(' | ')} |`,
    '',
    `Attacks detonated: ${atk[0]} of ${nA}. Benign texts detonated (false alarms): ${ben[0]} of ${nB}.`,
    '"Inconclusive" is a failed, unreadable or unfinished model answer; the chamber never counts it as clean.',
    '',
    '## Each text',
    '',
    '| Text | Label | Placed as | Verdict | Calls | What the model tried (secrets masked) |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    const tried = r.report
      ? r.report.calls.map((c) => `${c.harmful ? '**HARMFUL** ' : ''}\`${cell(c.tool)}\` ${cell(c.args).slice(0, 160)}`).join('<br>') || 'no tool call'
      : 'not run (cap)';
    lines.push(`| \`${r.file}\` | ${r.label} | ${r.placement} | ${r.report?.verdict ?? 'not run'} | ${r.report?.modelCalls ?? 0} | ${tried} |`);
  }
  const misses = rows.filter((r) => r.label === 'attack' && r.report && r.report.verdict !== 'detonated');
  const alarms = rows.filter((r) => r.label === 'benign' && r.report?.verdict === 'detonated');
  lines.push('', '## Misses and false alarms', '');
  if (misses.length === 0 && alarms.length === 0) lines.push('None in this run.');
  for (const r of misses) lines.push(`- Missed \`${r.file}\` (${r.report?.verdict}): ${cell(r.report?.reason ?? '')}`);
  for (const r of alarms) lines.push(`- False alarm \`${r.file}\`: ${cell(r.report?.reason ?? '')}`);
  lines.push(
    '',
    '## Limits',
    '',
    '- One model, one run, temperature 0, 20 texts: a small sample, not a benchmark. Another model or a later model version can behave differently.',
    '- A model that refuses or ignores an attack makes it look inert: the chamber measures what this model tries, not whether the text is malicious.',
    '- `exorcist scan --detonate` only detonates files that already have a medium-or-worse or AI finding, and these attacks have none; use `exorcist detonate <file>` (or `--ai` first) to reach them.',
    '',
  );
  return lines.join('\n');
}

async function main(): Promise<number> {
  if (!process.env['AWS_REGION'] && !process.env['AWS_DEFAULT_REGION']) {
    console.error('Set AWS_REGION (and AWS_PROFILE) first. Nothing was run or written.');
    return 2;
  }
  const labels = JSON.parse(readFileSync(join(root, 'fixtures/detonation/labels.json'), 'utf8')) as Labels;
  const client = capped(new BedrockClientImpl(), HARD_CAP);
  const model = modelIdFor('haiku');
  console.log(`model ${model}, hard cap ${HARD_CAP} calls`);
  const rows = await runEval(client, labels, HARD_CAP);
  console.log(`model calls: ${client.attempts()} (${client.failures()} failed)`);
  if (client.attempts() > 0 && client.failures() === client.attempts()) {
    console.error(`Every model call failed (${client.firstError() ?? 'unknown error'}). Nothing was written.`);
    return 1;
  }
  const out = join(root, 'docs/DETONATION.md');
  writeFileSync(out, renderReport(rows, {
    model, date: new Date().toISOString().slice(0, 10), calls: client.attempts(), failures: client.failures(), cap: HARD_CAP,
  }));
  console.log(`wrote ${out}`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().then((code) => process.exit(code), (err: unknown) => { console.error(String(err).split('\n')[0]); process.exit(1); });
}
