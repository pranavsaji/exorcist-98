// Generated from scripts/kiro-hook.sh; a test checks the two stay identical.
// `exorcist init` writes it to .exorcist/kiro-hook.sh. Kiro runs hook commands
// with a PATH that has no Node, so the hooks go through this script.
export const KIRO_HOOK_SCRIPT = [
  "#!/bin/sh",
  "# Exorcist 98: run a Kiro hook command with Node on PATH.",
  "#",
  "# Kiro runs hook commands with a minimal PATH (/usr/bin:/bin:/usr/sbin:/sbin),",
  "# so node, npx and pnpm installed with nvm, Homebrew, Volta, fnm or asdf are",
  "# not found. The hook then fails with \"command not found\", which Kiro does not",
  "# treat as a block, so the check silently never runs. This script finds Node",
  "# first, then runs the command with the hook event on stdin.",
  "#",
  "# Usage: sh kiro-hook.sh [--guard] <command> [args...]",
  "#   --guard  if Node cannot be found and the event is a git commit, block the",
  "#            commit (exit 2) instead of letting it through unchecked.",
  "# X98_NODE_DIRS (colon-separated) replaces the search list; used by tests.",
  "",
  "guard=0",
  "if [ \"$1\" = \"--guard\" ]; then guard=1; shift; fi",
  "input=$(cat)",
  "# A guard only ever acts on git commits; skip Node startup for every other command.",
  "if [ \"$guard\" = 1 ] && ! printf '%s' \"$input\" | grep -q 'commit'; then exit 0; fi",
  "",
  "node_dir=\"\"",
  "try_dir() {",
  "  if [ -z \"$node_dir\" ] && [ -n \"$1\" ] && [ -x \"$1/node\" ]; then node_dir=$1; fi",
  "}",
  "",
  "if [ -n \"${X98_NODE_DIRS+x}\" ]; then",
  "  old_ifs=$IFS; IFS=:",
  "  for d in $X98_NODE_DIRS; do try_dir \"$d\"; done",
  "  IFS=$old_ifs",
  "else",
  "  found=$(command -v node 2>/dev/null)",
  "  if [ -n \"$found\" ]; then node_dir=$(dirname \"$found\"); fi",
  "  if [ -n \"$HOME\" ] && [ -d \"$HOME/.nvm/versions/node\" ]; then",
  "    # Newest installed version first.",
  "    for v in $(ls -1 \"$HOME/.nvm/versions/node\" | sed 's/^v//' | sort -t. -k1,1nr -k2,2nr -k3,3nr); do",
  "      try_dir \"$HOME/.nvm/versions/node/v$v/bin\"",
  "    done",
  "  fi",
  "  try_dir \"$HOME/.volta/bin\"",
  "  try_dir \"$HOME/.local/share/fnm/aliases/default/bin\"",
  "  try_dir \"$HOME/Library/Application Support/fnm/aliases/default/bin\"",
  "  try_dir \"$HOME/.asdf/shims\"",
  "  try_dir \"/opt/homebrew/bin\"",
  "  try_dir \"/usr/local/bin\"",
  "fi",
  "",
  "log=\"$(dirname \"$0\")/kiro-hooks.log\"",
  "stamp=$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "",
  "if [ -z \"$node_dir\" ]; then",
  "  if [ \"$guard\" = 1 ] && printf '%s' \"$input\" | grep -Eq 'git[^\"]*commit'; then",
  "    echo \"Exorcist 98 blocked this commit: Node.js was not found, so staged files could not be checked for secrets. Install Node 20+ (or add it to /usr/local/bin) and try again.\" >&2",
  "    printf '%s %s node=missing exit=2\\n' \"$stamp\" \"$*\" >> \"$log\" 2>/dev/null",
  "    exit 2",
  "  fi",
  "  if [ \"$guard\" = 1 ]; then exit 0; fi",
  "  echo \"Exorcist 98 hook skipped: Node.js was not found. Install Node 20+.\" >&2",
  "  printf '%s %s node=missing exit=1\\n' \"$stamp\" \"$*\" >> \"$log\" 2>/dev/null",
  "  exit 1",
  "fi",
  "",
  "PATH=\"$node_dir:$PATH\"",
  "export PATH",
  "printf '%s' \"$input\" | \"$@\"",
  "status=$?",
  "printf '%s %s exit=%s\\n' \"$stamp\" \"$*\" \"$status\" >> \"$log\" 2>/dev/null",
  "exit $status",
].join('\n') + '\n';
