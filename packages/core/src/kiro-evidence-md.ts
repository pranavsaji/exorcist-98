/**
 * Renders docs/KIRO_EVIDENCE.md from the index scripts/kiro-evidence.mjs writes
 * (m13-kiro-evidence, KE-15 to KE-17, KE-27). Pure: no file access.
 */
import type { SessionRecord, Totals } from './kiro-evidence.js';

export type EvidenceIndex = { sessions: SessionRecord[]; totals: Totals };

/** Where transcripts live, relative to docs/KIRO_EVIDENCE.md. */
export const TRANSCRIPT_DIR = '../evidence/kiro-sessions';

const sum = (m: Record<string, number>): number => Object.values(m).reduce((a, b) => a + b, 0);

/** One-line, table-safe text: no pipes, newlines or markup that could break a row. */
function cell(text: string | null | undefined, fallback = 'unknown'): string {
  if (text === null || text === undefined || text.trim().length === 0) return fallback;
  return text.replace(/\s+/g, ' ').trim().replace(/[|\\`[\]<>]/g, (c) => `\\${c}`);
}

function transcriptLink(id: string): string {
  const file = `${encodeURIComponent(id)}.jsonl.gz`;
  return `[${cell(file)}](${TRANSCRIPT_DIR}/${file})`;
}

function breakdown(title: string, map: Record<string, number>): string[] {
  const entries = Object.entries(map).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  if (entries.length === 0) return [];
  return ['', `**${title}**`, '', '| Name | Count |', '| --- | ---: |', ...entries.map(([k, v]) => `| ${cell(k)} | ${v} |`)];
}

function hookBlockSection(sessions: SessionRecord[]): string[] {
  const blocks = sessions.flatMap((s) => s.hookBlockEvents.map((b) => ({ sessionId: s.id, ...b })));
  if (blocks.length === 0) return [];
  blocks.sort((a, b) => a.timestamp.localeCompare(b.timestamp) || a.sessionId.localeCompare(b.sessionId));
  const lines = [
    '',
    '## Hook blocks',
    '',
    'A hook block is a tool call that a `PreToolUse` hook stopped before it ran. Kiro does not record which hook stopped it, so each block is credited to the hook that ran directly before the denied result.',
    '',
  ];
  for (const b of blocks) {
    const tool = b.toolName === null ? 'a tool call' : `the \`${cell(b.toolName)}\` tool call`;
    lines.push(
      `- On ${cell(b.timestamp)}, in session \`${cell(b.sessionId)}\`, the \`${cell(b.hookName)}\` hook blocked ${tool}.`,
    );
  }
  return lines;
}

/** Build the whole evidence document. The same index always gives the same text. */
export function renderKiroEvidenceMd(index: EvidenceIndex): string {
  const { sessions, totals } = index;
  const out: string[] = [
    '# Kiro evidence',
    '',
    '<!-- Generated by scripts/kiro-evidence-md.ts from evidence/kiro-sessions/index.json. Do not edit by hand. -->',
    '',
    'These are the Kiro sessions that built this project, exported with secrets and home paths removed. Every number below is read from `evidence/kiro-sessions/index.json`.',
    '',
    '## Totals',
    '',
    '| Measure | Value |',
    '| --- | ---: |',
    `| Sessions kept | ${totals.sessionsKept} |`,
    `| Sessions skipped (other projects) | ${totals.sessionsSkipped} |`,
    `| Credits | ${totals.credits.toFixed(2)} |`,
    `| Tool calls | ${sum(totals.toolCalls)} |`,
    `| Hook runs | ${sum(totals.hookRuns)} |`,
    `| Hook blocks | ${sum(totals.hookBlocks)} |`,
    `| Events dropped (unparseable after redaction) | ${totals.eventsDroppedUnparseable} |`,
    ...breakdown('Tool calls by tool', totals.toolCalls),
    ...breakdown('Hook runs by hook', totals.hookRuns),
    ...breakdown('Hook blocks by hook', totals.hookBlocks),
    ...hookBlockSection(sessions),
    '',
    '## Sessions',
    '',
    '| Title | Mode | Started | Transcript |',
    '| --- | --- | --- | --- |',
    ...sessions.map(
      (s) => `| ${cell(s.title, 'untitled')} | ${cell(s.agentMode)} | ${cell(s.startTime)} | ${transcriptLink(s.id)} |`,
    ),
    '',
    '## Spec coverage',
    '',
    'Every spec other than `m10-kiro-gate` and `m13-kiro-evidence` predates requirement IDs and is outside the coverage of `scripts/spec-trace.mjs`.',
    '',
  ];
  return out.join('\n');
}
